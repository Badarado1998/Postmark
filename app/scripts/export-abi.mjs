// Writes src/chain/abi.ts from the Foundry artifact. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';
const artifact = JSON.parse(
  readFileSync(new URL('../../out/PostmarkEscrow.sol/PostmarkEscrow.json', import.meta.url)));
const body = JSON.stringify(artifact.abi, null, 2);
writeFileSync(new URL('../src/chain/abi.ts', import.meta.url),
  `// Generated by scripts/export-abi.mjs from out/PostmarkEscrow.sol/PostmarkEscrow.json.\n` +
  `// Do not edit; run \`npm run export-abi\`.\n` +
  `export const postmarkEscrowAbi = ${body} as const;\n`);
console.log(`abi.ts written (${artifact.abi.length} entries)`);
